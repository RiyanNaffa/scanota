def translate(lang: str, key: str, **values: object) -> str:
    """Text for `key` in `lang`; falls back to Indonesian, then to the key itself."""
    text = STRINGS.get(lang, {}).get(key) or STRINGS[DEFAULT_LANG].get(key) or key
    return text.format(**values) if values else text
